test_that("versioned catalogues distinguish linkage findings and lexical classifications", {
  rules <- validation_rules()
  expect_equal(rules$catalogue_version, "linkage-dates-1.0")
  expect_setequal(names(rules$rules), c("PRE-01", sprintf("LNK-%02d", 1:8), "TMP-00", "TMP-01", "TMP-02", "TMP-03", "TMP-08"))
  expect_equal(rules$rules[["LNK-02"]]$severity, "error")
  expect_true(rules$rules[["LNK-06"]]$mandatory_when_applicable)
  expect_false(rules$rules[["LNK-08"]]$mandatory_when_applicable)
  expect_equal(rules$rules[["LNK-08"]]$severity, "warning")
  expect_null(rules$rules[["TMP-02"]]$severity)
  expect_false(date_patterns()$calendar_validation)
  expect_true(date_patterns()$provisional)
  expect_equal(date_patterns()$patterns[["ymd-dash"]]$example, "2020-03-15")
  expect_error(validation_rules("../other"), "version")
  expect_error(date_patterns("missing"), "version")
})

test_that("mapping contracts preserve positions, duplicate headers and named component roles", {
  t <- new_validation_table("version-a", "resource-a", c("date", "date", "anno", "giorno", "mese"))
  m <- new_date_mapping(t, "sampling", "sampling_date", c(month = 4L, year = 2L, day = 3L),
    "user", "reviewer", "Checked sampling protocol", TRUE)
  expect_equal(m$columns$year$position, 2L)
  expect_equal(m$columns$day$original_header, "giorno")
  expect_equal(m$columns$month$position, 4L)
  expect_equal(m$table$table_id, "resource-a:table")
  first <- new_date_mapping(t, "first", "analysis_date", c(value = 0L), "suggested", "detector", "Header candidate")
  expect_false(first$confirmed)
  expect_error(new_date_mapping(t, "x", "date", c(value = 9L), "user", "a", "e", TRUE), "position")
  expect_error(new_date_mapping(t, "x", "date", c(day = 1L, month = 1L, year = 2L), "user", "a", "e", TRUE), "distinct")
  expect_error(new_date_mapping(t, "x", "date", c(value = 0L), "suggested", "a", "e", TRUE), "suggested")
  expect_error(new_date_mapping(t, "x", "date", c(value = 0L), NULL, "a", "e", TRUE), "source")
  expect_error(new_date_mapping(t, "x", "date", c(value = 0L), "des", "a", "e", TRUE), "source")
  expect_error(new_date_mapping(t, "x", "date", c(value = 0L), "user", "a", "e", TRUE, "DMY"), "evidence")
  ordered <- new_date_mapping(t, "x", "date", c(value = 1L), "user", "a", "e", TRUE, "DMY", "Publisher convention")
  expect_equal(ordered$date_order, "DMY")
})

test_that("descriptor linkage uses column zero and stays inside one archive", {
  core <- new_validation_table("version-a", "resource-a", c("id", "occurrenceID"), "occurrence.txt")
  ext <- new_validation_table("version-a", "resource-a", c("coreid", "value"), "measurement.txt")
  link <- new_linkage_mapping(core, 0L, ext, 0L, "relationship", "publisher", "meta.xml id/coreid declarations", TRUE)
  expect_equal(link$core$column$position, 0L)
  expect_equal(link$core$column$original_header, "id")
  expect_equal(link$extension$column$position, 0L)
  expect_equal(link$core$table$member, "occurrence.txt")
  foreign <- new_validation_table("version-b", "resource-b", c("coreid"), "measurement.txt")
  expect_error(new_linkage_mapping(core, 0, foreign, 0, "bad", "a", "e", TRUE), "archive")
  expect_error(new_linkage_mapping(core, 0, core, 0, "bad", "a", "e", TRUE), "different")
})

test_that("specifications freeze catalogues and reject conflicting table declarations", {
  t <- new_validation_table("v", "r", c("date", "other"))
  a <- new_date_mapping(t, "one", "sampling_date", c(value = 0L), "user", "a", "e", TRUE)
  b <- new_date_mapping(t, "two", "analysis_date", c(value = 1L), "user", "a", "e", TRUE)
  spec <- new_validation_spec(list(a, b))
  expect_equal(spec$rules$snapshot$catalogue_version, "linkage-dates-1.0")
  expect_match(spec$patterns$sha256, "^[a-f0-9]{64}$")
  expect_equal(decode_json(json_text(spec)), spec)
  expect_error(new_validation_spec(list(a, a)), "mapping_id")
  altered <- b; altered$table$headers[[1]] <- "different"
  expect_error(new_validation_spec(list(a, altered)), "table")
  expect_error(new_validation_spec(list(a), enabled_rules = c("TMP-99")), "rule")
})
