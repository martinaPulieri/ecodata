test_that("date result records preserve split values, widths, provenance and incomplete components", {
  repo <- new_test_repo(); f <- contract_mapping(repo)
  cfg <- make_config(repo, f$version$version_id, validation_spec = new_validation_spec(list(f$mapping)))
  ctx <- freeze_validation_context(repo, cfg$config_id)
  row <- new_date_result(ctx, "sampling", 1L, c(year = "2020", day = "7", month = "03"), "recognised", "split-numeric")
  expect_equal(row$original_values$month, "03")
  expect_equal(row$observed_widths$day, 1L)
  expect_equal(row$observed_widths$month, 2L)
  expect_equal(row$mapping$columns$year$position, 0L)
  expect_equal(row$rule_id, "TMP-03")
  expect_match(row$row_locator, ":row:1$")
  expect_equal(row$pattern_catalogue_version, "date-patterns-0.1")
  expect_equal(row$mapping$actor_id, "tester")
  incomplete <- new_date_result(ctx, "sampling", 2L, c(year = "2020", day = "7", month = ""), "incomplete")
  expect_equal(unlist(incomplete$missing_components), "month")
  missing <- new_date_result(ctx, "sampling", 3L, c(year = "", day = " ", month = "\t"), "missing")
  expect_setequal(unlist(missing$missing_components), c("day", "month", "year"))
  expect_equal(missing$original_values$month, "\t")
  summary <- summarise_date_results(ctx, "sampling", list(row, incomplete, missing), 3L)
  expect_equal(summary$counts$recognised, 1L)
  expect_equal(summary$counts$incomplete, 1L)
  expect_equal(summary$counts$missing, 1L)
  expect_error(summarise_date_results(ctx, "sampling", list(row, row), 2L), "row")
  expect_error(summarise_date_results(ctx, "sampling", list(row), 3L), "population")
  expect_error(new_date_result(ctx, "sampling", 4, c(year = "2020", day = "7", month = ""), "recognised", "split-numeric"), "component")
})

test_that("single-field results retain ambiguity without calendar or value conversion", {
  repo <- new_test_repo(); f <- contract_mapping(repo)
  field <- new_date_mapping(f$table, "analysis", "analysis_date", c(value = 3), "user", "tester", "Confirmed", TRUE)
  suggestion <- new_date_mapping(f$table, "candidate", "unknown_date", c(value = 3), "suggested", "detector", "Unconfirmed")
  cfg <- make_config(repo, f$version$version_id, validation_spec = new_validation_spec(list(field, suggestion)))
  ctx <- freeze_validation_context(repo, cfg$config_id)
  a <- new_date_result(ctx, "analysis", 1, c(value = "03/04/2020"), "ambiguous", c("dmy-slash", "mdy-slash"))
  expect_length(a$candidates, 2L)
  expect_equal(a$original_values$value, "03/04/2020")
  impossible <- new_date_result(ctx, "analysis", 2, c(value = "2020-02-30"), "recognised", "ymd-dash")
  expect_equal(impossible$status, "recognised") # contract, not calendar assessment
  expect_equal(impossible$original_values$value, "2020-02-30")
  interval <- new_date_result(ctx, "analysis", 3, c(value = "2020-03-15/2020-03-20"), "recognised", "ymd-interval")
  expect_equal(unlist(interval$candidates[[1]]$pattern$endpoint_patterns), c("ymd-dash", "ymd-dash"))
  expect_error(new_date_result(ctx, "analysis", 4, c(value = "NA"), "missing"), "missing")
  expect_error(new_date_result(ctx, "analysis", 4, c(value = "date"), "ambiguous", "ymd-dash"), "candidate")
  expect_error(new_date_result(ctx, "candidate", 1, c(value = "2020"), "recognised", "year"), "confirmed")
  expect_error(new_date_result(ctx, "analysis", 1, c(value = "2020"), NULL, "year"), "status")
  expect_error(new_date_result(ctx, "analysis", 1, c(value = "2020"), "rec", "year"), "status")
  skipped <- new_date_result(ctx, "candidate", 1, c(value = "2020"), "not_evaluated", reason = "Mapping not confirmed")
  expect_equal(skipped$rule_id, "TMP-00")
  altered <- ctx; altered$config_id <- "another"
  expect_error(new_date_result(altered, "analysis", 1, c(value = "2020"), "recognised", "year"), "hash")
})

test_that("linkage contracts count each extension row once and keep group findings separate", {
  repo <- new_test_repo(); v <- register_input(write_fixture("archive placeholder", ".zip"), list(), repo)
  core <- new_validation_table(v$version_id, v$resource_ids[1], "id", "core.txt")
  ext <- new_validation_table(v$version_id, v$resource_ids[1], "coreid", "ext.txt")
  mapping <- new_linkage_mapping(core, 0, ext, 0, "relation", "tester", "Descriptor declaration", TRUE)
  cfg <- make_config(repo, v$version_id, validation_spec = new_validation_spec(linkage_mappings = list(mapping)))
  ctx <- freeze_validation_context(repo, cfg$config_id)
  refs <- c("001", "001", "002", "003", "")
  outcomes <- c("linked", "linked", "ambiguous", "unresolved_reference", "missing_reference")
  targets <- list(1, 1, c(2, 3), numeric(), numeric())
  rows <- lapply(1:5, function(i) new_linkage_result(ctx, "relation", i, refs[i], outcomes[i], targets[[i]]))
  summary <- summarise_linkage_results(ctx, "relation", rows, 5)
  expect_equal(unlist(summary$counts), c(ambiguous = 1, linked = 2, missing_reference = 1, not_evaluated = 0, unresolved_reference = 1))
  expect_equal(rows[[3]]$rule_id, "LNK-06")
  expect_length(rows[[3]]$candidate_core_locators, 2L)
  expect_error(new_linkage_result(ctx, "relation", 1, "001", "linked", c(1, 2)), "candidate")
  expect_error(new_linkage_result(ctx, "relation", 1, "NA", "missing_reference"), "missing")
  expect_error(new_linkage_result(ctx, "relation", 1, "001", NULL, 1), "outcome")
  finding <- new_validation_finding(ctx, "LNK-03", core$table_id, c(2, 3), c("002", "002"), "Repeated key group")
  expect_equal(finding$severity, "error")
  expect_length(finding$row_locators, 2L)
  expect_equal(finding$original_values[[1]], "002")
  expect_equal(finding$mapping_id, "relation")
  expect_error(new_validation_finding(ctx, "LNK-03", core$table_id, 2, "002", "Not a group"), "at least two")
  expect_error(new_validation_finding(ctx, "LNK-03", ext$table_id, c(2, 3), c("002", "002"), "Wrong target"), "linkage")
  expect_error(new_validation_finding(ctx, "LNK-03", core$table_id, c(2, 3), c("002", "003"), "Different keys"), "same")
})

test_that("check results separate execution coverage and prerequisite limitations", {
  repo <- new_test_repo(); f <- contract_mapping(repo)
  cfg <- make_config(repo, f$version$version_id, validation_spec = new_validation_spec(list(f$mapping)))
  ctx <- freeze_validation_context(repo, cfg$config_id)
  failed <- new_check_result(ctx, "TMP-02", f$table$table_id, "applicable", "failed", 10, 3, "Read failure after three rows")
  expect_equal(failed$coverage, "partial")
  expect_equal(failed$execution_state, "failed")
  skipped <- new_check_result(ctx, "LNK-01", character(), "prerequisites_missing", "not_started", NULL, 0, "No extension declaration")
  expect_equal(skipped$coverage, "unknown")
  expect_error(new_check_result(ctx, "TMP-02", f$table$table_id, "applicable", "completed", 10, 11), "population")
  expect_error(new_check_result(ctx, "TMP-02", f$table$table_id, "not_applicable", "completed", 10, 10), "not_started")
  expect_error(new_check_result(ctx, "TMP-02", f$table$table_id, "applicable", "failed", 10, 0), "reason")
  expect_error(new_check_result(ctx, "TMP-99", f$table$table_id, "applicable", "completed", 1, 1), "rule")
  expect_error(new_check_result(ctx, "TMP-02", f$table$table_id, NULL, "completed", 1, 1), "applicability")
  expect_error(new_check_result(ctx, "TMP-02", f$table$table_id, "applicable", NULL, 1, 1), "execution_state")
  expect_error(new_validation_finding(ctx, "LNK-03", f$table$table_id, c(1, 2), c("same", "same"), "No linkage declared"), "linkage")
})

test_that("summaries retain zero populations and reject altered or mixed-source records", {
  repo <- new_test_repo(); f <- contract_mapping(repo)
  cfg <- make_config(repo, f$version$version_id, validation_spec = new_validation_spec(list(f$mapping)))
  ctx <- freeze_validation_context(repo, cfg$config_id)
  zero <- summarise_date_results(ctx, "sampling", list(), 0)
  expect_equal(sum(unlist(zero$counts)), 0)
  row <- new_date_result(ctx, "sampling", 1, c(day = "01", month = "03", year = "2020"), "recognised", "split-numeric")
  changed <- row; changed$original_values$day <- "02"
  expect_error(summarise_date_results(ctx, "sampling", list(changed), 1), "hash")
  second <- contract_mapping(repo)
  other_cfg <- make_config(repo, second$version$version_id, validation_spec = new_validation_spec(list(second$mapping)))
  other_ctx <- freeze_validation_context(repo, other_cfg$config_id)
  other_row <- new_date_result(other_ctx, "sampling", 1, c(day = "01", month = "03", year = "2020"), "recognised", "split-numeric")
  expect_error(summarise_date_results(ctx, "sampling", list(other_row), 1), "another context")
  expect_error(new_date_result(ctx, "sampling", 1, c(day = "01", month = "03", year = NA_character_), "recognised", "split-numeric"), "original text")
  expect_error(new_date_result(ctx, "sampling", 0, c(day = "01", month = "03", year = "2020"), "recognised", "split-numeric"), "positive")
  expect_error(new_date_result(ctx, "sampling", 1, c(day = "01", month = "03", year = "2020"), "recognised", "unknown-pattern"), "pattern")
})
