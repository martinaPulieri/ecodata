test_that("validation definitions append, survive restart and inherit through existing edits", {
  repo <- new_test_repo()
  f <- contract_mapping(repo)
  first <- make_config(repo, f$version$version_id)
  expect_null(first$validation_spec)
  spec <- new_validation_spec(list(f$mapping))
  second <- make_config(repo, f$version$version_id, expected_revision = 1L, validation_spec = spec)
  expect_equal(second$validation_spec, spec)
  third <- redetect_configuration(repo, second$config_id, f$version$resource_ids[1], "tester")
  expect_equal(third$validation_spec, spec)
  fourth <- confirm_profile(f$version$version_id, "generic_tabular", "Explicit generic profile", 3L, repo, "tester")
  expect_equal(fourth$validation_spec, spec)
  expect_null(get_configuration(repo, first$config_id)$validation_spec)
  close_repository(repo)
  reopened <- open_repository(repo$root)
  withr::defer(close_repository(reopened))
  context <- freeze_validation_context(reopened, fourth$config_id)
  expect_equal(context$validation_spec, spec)
  expect_equal(context$config_id, fourth$config_id)
  expect_equal(context$config_hash, fourth$context_hash)
  expect_equal(context, decode_json(json_text(context)))
  expect_true(verify_input(reopened, f$version$version_id)$ok)
  expect_error(freeze_validation_context(reopened, first$config_id), "specification")
})

test_that("foreign mappings, altered catalogues and stale writes do not append snapshots", {
  repo <- new_test_repo()
  a <- contract_mapping(repo)
  b <- register_fixture(repo)
  spec <- new_validation_spec(list(a$mapping))
  expect_error(make_config(repo, b$version_id, validation_spec = spec), "different version")
  unknown <- new_validation_table(a$version$version_id, "resource-not-owned", "date")
  unknown_mapping <- new_date_mapping(unknown, "foreign-resource", "sampling_date", c(value = 0), "user", "tester", "Declaration only", TRUE)
  expect_error(make_config(repo, a$version$version_id, validation_spec = new_validation_spec(list(unknown_mapping))), "unknown resource")
  corrupt <- spec; corrupt$rules$snapshot$rules[["LNK-02"]]$severity <- "information"
  expect_error(make_config(repo, a$version$version_id, validation_spec = corrupt), "snapshot")
  cfg <- make_config(repo, a$version$version_id, validation_spec = spec)
  expect_error(make_config(repo, a$version$version_id, validation_spec = spec), "stale")
  set_workspace_state(repo, a$version$version_id, "removed", 0L, "contract-remove", "tester")
  expect_error(freeze_validation_context(repo, cfg$config_id), "removed")
  expect_error(make_config(repo, a$version$version_id, expected_revision = 1L, validation_spec = spec), "removed")
  expect_equal(nrow(list_configurations(repo, a$version$version_id)), 1L)
})

test_that("explicit empty specifications clear mappings without erasing older versions", {
  repo <- new_test_repo()
  f <- contract_mapping(repo)
  first <- make_config(repo, f$version$version_id, validation_spec = new_validation_spec(list(f$mapping)))
  second <- make_config(repo, f$version$version_id, expected_revision = 1L, validation_spec = new_validation_spec())
  expect_length(second$validation_spec$date_mappings, 0L)
  expect_length(get_configuration(repo, first$config_id)$validation_spec$date_mappings, 1L)
})
