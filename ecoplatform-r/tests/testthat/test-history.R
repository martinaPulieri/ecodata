test_that("operation submission is idempotent and binds frozen input configuration", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  first <- submit_operation(repo, v$version_id, cfg$config_id, "inspect", "request-1", "tester")
  again <- submit_operation(repo, v$version_id, cfg$config_id, "inspect", "request-1", "tester")
  expect_equal(first$operation_id, again$operation_id)
  revised <- make_config(repo, v$version_id, expected_revision = 1L)
  expect_error(submit_operation(repo, v$version_id, revised$config_id, "inspect", "request-1", "tester"), "different")
  expect_equal(get_operation(repo, first$operation_id)$configuration$config_id, cfg$config_id)
  expect_equal(nrow(list_operations(repo)), 1L)
})

test_that("history enforces transitions and retains interruptions without automatic recovery", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  op <- submit_operation(repo, v$version_id, cfg$config_id, "inspect", "history", "tester")
  expect_error(record_operation_event(repo, op$operation_id, "completed", "tester"), "transition")
  record_operation_event(repo, op$operation_id, "running", "tester")
  close_repository(repo)
  reopened <- open_repository(repo$root)
  withr::defer(close_repository(reopened))
  expect_equal(list_pending_operations(reopened)$status, "running")
  record_operation_event(reopened, op$operation_id, "interrupted", "tester", "worker stopped")
  history <- get_operation(reopened, op$operation_id)
  expect_equal(history$events$status, c("queued", "running", "interrupted"))
  expect_error(record_operation_event(reopened, op$operation_id, "running", "tester"), "transition")
  expect_equal(nrow(list_pending_operations(reopened)), 0L)
  expect_error(DBI::dbExecute(reopened$con, "DELETE FROM operation_events"), "immutable")
})

test_that("operation submission rejects cross-version configurations and incomplete resources", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  other <- register_fixture(repo)
  expect_error(submit_operation(repo, other$version_id, cfg$config_id, "inspect", "wrong-version", "tester"), "version")
  incomplete <- register_input(write_fixture(), list(), repo, acquisition_status = "incomplete")
  icfg <- make_config(repo, incomplete$version_id)
  expect_error(submit_operation(repo, incomplete$version_id, icfg$config_id, "validation", "partial", "tester"), "incomplete")
  expect_silent(submit_operation(repo, incomplete$version_id, icfg$config_id, "inspect", "partial-inspect", "tester"))
})

test_that("opening and backup preserve integrity and reject unsupported database versions", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  backup <- tempfile(fileext = ".sqlite")
  backup_repository(repo, backup)
  con <- DBI::dbConnect(RSQLite::SQLite(), backup)
  withr::defer(DBI::dbDisconnect(con))
  expect_equal(DBI::dbGetQuery(con, "SELECT count(*) AS n FROM dataset_versions")$n, 1L)
  expect_equal(DBI::dbGetQuery(con, "PRAGMA integrity_check")[[1]], "ok")
  expect_error(DBI::dbExecute(repo$con, "INSERT INTO resources (resource_id, version_id, ordinal, original_name, owned_relative_path, sha256, size_bytes, acquisition_status, integrity_status) VALUES ('bad','missing',1,'x','x','x',1,'unknown','verified')"), "FOREIGN KEY")
  expect_error(migrate_repository(repo$con, statements = c("CREATE TABLE rollback_witness (id TEXT)", "INVALID SQL"), target_version = 3L), "syntax")
  expect_false(DBI::dbExistsTable(repo$con, "rollback_witness"))
  expect_equal(DBI::dbGetQuery(repo$con, "PRAGMA user_version")[[1]], 2L)
  DBI::dbExecute(repo$con, "PRAGMA user_version = 999")
  close_repository(repo)
  expect_error(open_repository(repo$root), "newer")
})
