# Removing the projection must never delete immutable data or sibling versions.
test_that("workspace removal is version scoped, reversible and persistent", {
  repo <- new_test_repo()
  path <- write_fixture()
  v <- register_input(c(path, path), list(title = "Two files"), repo,
    original_names = c("same.csv", "same.csv"))
  sibling <- register_fixture(repo, parent_version_id = v$version_id)
  cfg <- make_config(repo, v$version_id)
  run <- run_workspace_inspection(repo, v$version_id, cfg$config_id, "tester")
  manifest <- get_input(repo, v$version_id)
  configs <- list_configurations(repo, v$version_id)
  operations <- list_operations(repo)
  expect_equal(get_workspace_state(repo, v$version_id)$revision, 0L)
  expect_error(set_workspace_state(repo, v$version_id, "removed", 0L, " ", "tester"), "request_id")
  removed <- set_workspace_state(repo, v$version_id, "removed", 0L, "remove-one", "tester")
  expect_equal(removed$revision, 1L)
  expect_equal(list_workspace_inputs(repo)$version_id, sibling$version_id)
  expect_equal(list_workspace_inputs(repo, "removed")$version_id, v$version_id)
  expect_equal(nrow(list_inputs(repo)), 2L)
  expect_equal(get_input(repo, v$version_id), manifest)
  expect_equal(list_configurations(repo, v$version_id), configs)
  expect_equal(list_operations(repo), operations)
  expect_true(verify_input(repo, v$version_id)$ok)
  expect_equal(get_operation(repo, run$operation_id)$configuration$config_id, cfg$config_id)
  expect_error(DBI::dbExecute(repo$con, "DELETE FROM workspace_lifecycle_events"), "immutable")
  expect_error(DBI::dbExecute(repo$con, "UPDATE workspace_lifecycle_events SET state='active'"), "immutable")
  close_repository(repo)
  reopened <- open_repository(repo$root)
  withr::defer(close_repository(reopened))
  expect_equal(get_workspace_state(reopened, v$version_id)$state, "removed")
  restored <- set_workspace_state(reopened, v$version_id, "active", 1L, "restore-one", "tester")
  expect_equal(restored$revision, 2L)
  expect_setequal(list_workspace_inputs(reopened)$version_id, c(v$version_id, sibling$version_id))
  expect_equal(list_workspace_events(reopened, v$version_id)$state, c("removed", "active"))
  expect_true(verify_input(reopened, v$version_id)$ok)
})

test_that("concurrent removals append once and removal cannot race a new operation", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  args <- list(root = repo$root, version = v$version_id, config = cfg$config_id)
  results <- concurrent_workers(function(x) {
    repo <- open_repository(x$root)
    on.exit(close_repository(repo))
    tryCatch({
      if (x$action == "remove") set_workspace_state(repo, x$version, "removed", 0L, "racing-removal", "tester")
      else submit_operation(repo, x$version, x$config, "inspect", "racing-operation", "tester")
      "ok"
    }, error = conditionMessage)
  }, list(c(args, list(action = "remove")), c(args, list(action = "submit"))))
  expect_equal(sum(vapply(results, identical, logical(1), "ok")), 1L)
  expect_false(get_workspace_state(repo, v$version_id)$state == "removed" && nrow(list_pending_operations(repo)) > 0L)
  # A second version exercises two writers removing with the same displayed
  # revision but different keys: exactly one may append.
  second <- register_fixture(repo)
  results <- concurrent_workers(function(x) {
    repo <- open_repository(x$root)
    on.exit(close_repository(repo))
    tryCatch({set_workspace_state(repo, x$version, "removed", 0L, x$key, "tester"); "ok"}, error = conditionMessage)
  }, lapply(c("one", "two"), function(key) list(root = repo$root, version = second$version_id, key = key)))
  expect_equal(sum(vapply(results, identical, logical(1), "ok")), 1L)
  expect_equal(nrow(list_workspace_events(repo, second$version_id)), 1L)
})

test_that("pending operations block removal and idempotent history remains accessible", {
  repo <- new_test_repo()
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  op <- submit_operation(repo, v$version_id, cfg$config_id, "inspect", "old-request", "tester")
  expect_error(set_workspace_state(repo, v$version_id, "removed", 0L, "rm", "tester"), "queued|running")
  record_operation_event(repo, op$operation_id, "running", "tester")
  expect_error(set_workspace_state(repo, v$version_id, "removed", 0L, "rm", "tester"), "queued|running")
  record_operation_event(repo, op$operation_id, "completed", "tester")
  removed <- set_workspace_state(repo, v$version_id, "removed", 0L, "rm", "tester")
  expect_equal(set_workspace_state(repo, v$version_id, "removed", 0L, "rm", "tester"), removed)
  expect_equal(nrow(list_workspace_events(repo, v$version_id)), 1L)
  expect_error(set_workspace_state(repo, v$version_id, "active", 1L, "rm", "tester"), "different")
  expect_equal(submit_operation(repo, v$version_id, cfg$config_id, "inspect", "old-request", "tester")$operation_id, op$operation_id)
  expect_error(submit_operation(repo, v$version_id, cfg$config_id, "inspect", "new-request", "tester"), "removed")
  expect_error(make_config(repo, v$version_id, expected_revision = 1L), "removed")
  expect_error(redetect_configuration(repo, cfg$config_id, v$resource_ids[1], "tester"), "removed")
  expect_equal(nrow(list_operations(repo)), 1L)
  expect_equal(nrow(list_configurations(repo, v$version_id)), 1L)
})

test_that("lifecycle revisions reject stale confirmations and remove restore ABA writes", {
  repo <- new_test_repo()
  other <- open_repository(repo$root)
  withr::defer(close_repository(other))
  v <- register_fixture(repo)
  cfg <- make_config(repo, v$version_id)
  set_workspace_state(other, v$version_id, "removed", 0L, "rm-other", "other")
  expect_error(set_workspace_state(repo, v$version_id, "removed", 0L, "stale", "tester"), "stale")
  set_workspace_state(other, v$version_id, "active", 1L, "restore-other", "other")
  expect_error(set_workspace_state(repo, v$version_id, "removed", 0L, "stale", "tester"), "stale")
  expect_error(save_configuration(repo, v$version_id, actor_id = "tester", expected_revision = 1L, expected_workspace_revision = 0L), "stale")
  expect_error(submit_operation(repo, v$version_id, cfg$config_id, "inspect", "stale-op", "tester", expected_workspace_revision = 0L), "stale")
  expect_error(set_workspace_state(repo, v$version_id, "active", 2L, "noop", "tester"), "already")
  expect_error(set_workspace_state(repo, v$version_id, "removed", -1L, "bad", "tester"), "revision")
  expect_error(set_workspace_state(repo, "missing", "removed", 0L, "missing", "tester"), "Unknown")
  expect_equal(nrow(list_workspace_events(repo, v$version_id)), 2L)
})

test_that("registered v1 upgrade preserves data and keeps a verified v1 backup", {
  root <- tempfile("migration-v1-")
  dir.create(file.path(root, "database"), recursive = TRUE)
  con <- DBI::dbConnect(RSQLite::SQLite(), file.path(root, "database", "history.sqlite"))
  migrate_repository(con, target_version = 1L)
  DBI::dbExecute(con, "INSERT INTO datasets VALUES ('legacy-dataset','then')")
  DBI::dbExecute(con, "INSERT INTO dataset_versions VALUES ('legacy-version','legacy-dataset',NULL,'{}','then')")
  DBI::dbDisconnect(con)
  repo <- open_repository(root)
  withr::defer(close_repository(repo))
  expect_equal(DBI::dbGetQuery(repo$con, "PRAGMA user_version")[[1]], 2L)
  expect_equal(list_workspace_inputs(repo)$version_id, "legacy-version")
  backup <- list.files(file.path(root, "backups"), "[.]sqlite$", full.names = TRUE)
  expect_length(backup, 1L)
  old <- DBI::dbConnect(RSQLite::SQLite(), backup)
  withr::defer(DBI::dbDisconnect(old))
  expect_equal(DBI::dbGetQuery(old, "PRAGMA user_version")[[1]], 1L)
  expect_equal(DBI::dbGetQuery(old, "PRAGMA integrity_check")[[1]], "ok")
  expect_equal(DBI::dbGetQuery(old, "SELECT dataset_id FROM datasets")$dataset_id, "legacy-dataset")
})
