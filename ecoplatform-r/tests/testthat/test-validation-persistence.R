test_that("v2 upgrades atomically with a verified v2 backup and preserved records", {
  root <- tempfile("validation-v2-")
  dir.create(file.path(root, "database"), recursive = TRUE)
  con <- DBI::dbConnect(RSQLite::SQLite(), file.path(root, "database", "history.sqlite"))
  migrate_repository(con, target_version = 2L)
  DBI::dbExecute(con, "INSERT INTO datasets VALUES ('old','then')")
  DBI::dbExecute(con, "INSERT INTO dataset_versions VALUES ('old-version','old',NULL,'{}','then')")
  DBI::dbDisconnect(con)
  repo <- open_repository(root)
  withr::defer(close_repository(repo))
  expect_equal(DBI::dbGetQuery(repo$con, "PRAGMA user_version")[[1]], 3L)
  expect_true(DBI::dbExistsTable(repo$con, "validation_results"))
  expect_equal(list_inputs(repo)$version_id, "old-version")
  backups <- list.files(file.path(root, "backups"), "[.]sqlite$", full.names = TRUE)
  expect_length(backups, 1)
  old <- DBI::dbConnect(RSQLite::SQLite(), backups[[1]])
  withr::defer(DBI::dbDisconnect(old))
  expect_equal(DBI::dbGetQuery(old, "PRAGMA user_version")[[1]], 2L)
  expect_equal(DBI::dbGetQuery(old, "PRAGMA integrity_check")[[1]], "ok")
})

test_that("validation submission is atomic, frozen and idempotent across reopen", {
  repo <- new_test_repo()
  f <- full_fixture(repo, full_archive())
  a <- submit_validation_run(repo, f$v$version_id, f$cfg$config_id, "tester", "same-request", 0L)
  b <- submit_validation_run(repo, f$v$version_id, f$cfg$config_id, "tester", "same-request", 0L)
  expect_equal(a$operation_id, b$operation_id)
  expect_equal(nrow(list_operations(repo)), 1)
  expect_equal(nrow(list_validation_runs(repo)), 1)
  expect_error(submit_validation_run(repo, f$v$version_id, f$cfg$config_id, "tester", "same-request", 0L,
    families = "dates"), "different")
  expect_error(set_workspace_state(repo, f$v$version_id, "removed", 0L, "blocked", "tester"), "queued or running")
  request <- get_validation_run(repo, a$operation_id)
  expect_equal(request$frozen$config_hash, f$cfg$context_hash)
  expect_equal(request$frozen$resources[[1]]$sha256, get_input(repo, f$v$version_id)$resources$sha256)
  close_repository(repo)
  reopened <- open_repository(repo$root)
  withr::defer(close_repository(reopened))
  expect_equal(get_validation_run(reopened, a$operation_id)$frozen, request$frozen)
  expect_equal(list_pending_operations(reopened)$status, "queued")
})

test_that("persisted linkage/date rows, findings and summaries reconcile and survive removal", {
  repo <- new_test_repo()
  f <- linkage_engine_fixture(repo)
  op <- submit_validation_run(repo, f$v$version_id, f$cfg$config_id, "tester", "persisted", 0L)
  execute_validation_run(repo$root, op$operation_id, "synthetic-worker")
  run <- get_validation_run(repo, op$operation_id)
  expect_equal(run$status, "completed_with_limitations", info=utils::tail(run$events$reason,1)) # extension has no date role
  result <- get_validation_result(repo, op$operation_id)
  expect_equal(result$families$linkage$mappings[[1]]$summary$counts$linked, 4)
  dates <- query_validation_details(repo, op$operation_id, "dates", page_size = 3L)
  expect_equal(dates$total, 7)
  expect_length(dates$records, 3)
  next_page <- query_validation_details(repo, op$operation_id, "dates", page = 2L, page_size = 3L)
  expect_equal(next_page$records[[1]]$row_number, 4)
  links <- query_validation_details(repo, op$operation_id, "linkage")
  expect_equal(links$total, 9)
  findings <- query_validation_details(repo, op$operation_id, "findings")
  expect_equal(findings$total, 10)
  expect_true(DBI::dbGetQuery(repo$con, "SELECT count(*) AS n FROM validation_finding_targets")$n >= 10)
  expect_equal(get_validation_summary(repo, op$operation_id)$date_counts$recognised, 7)
  expect_error(DBI::dbExecute(repo$con, "DELETE FROM validation_rows"), "immutable")
  expect_error(DBI::dbExecute(repo$con, "UPDATE validation_results SET result_hash = 'bad'"), "immutable")
  set_workspace_state(repo, f$v$version_id, "removed", 0L, "remove-after", "tester")
  expect_equal(get_validation_result(repo, op$operation_id), result)
  expect_true(verify_input(repo, f$v$version_id)$ok)
  expect_equal(nrow(list_configurations(repo, f$v$version_id)), 1)
  close_repository(repo)
  reopened <- open_repository(repo$root)
  withr::defer(close_repository(reopened))
  expect_equal(get_validation_result(reopened, op$operation_id), result)
})
