#' Build the local input workspace interface
#' @param id Shiny module namespace.
#' @return Shiny HTML user interface. All assets are served locally.
#' @export
workspace_ui <- function(id = "workspace") {
  ns <- shiny::NS(id)
  shiny::fluidPage(lang = "en",
    theme = bslib::bs_theme(version = 5, primary = "#185e50", base_font = "system-ui"),
    shiny::includeCSS(system.file("www", "workspace.css", package = "ecodata", mustWork = TRUE)),
    shiny::tags$header(class = "app-header",
      shiny::div(class = "brand", shiny::span(class = "brand-mark", shiny::icon("leaf")),
        shiny::div(shiny::strong("ecodata"), shiny::span("Ecological data workspace"))),
      shiny::span(class = "local-badge", shiny::span(class = "status-dot"), "Running locally")),
    shiny::div(class = "page-intro",
      shiny::div(shiny::div(class = "eyebrow", "INPUT AND TRACEABILITY"), shiny::h1("Your workspace"),
        shiny::p("Register files, configure how they are read and trace every step.")),
      shiny::span(class = "stage-badge", "01 / Data preparation")),
    shiny::uiOutput(ns("metrics")), shiny::uiOutput(ns("notice")), shiny::uiOutput(ns("undo_removal")),
    shiny::div(class = "workspace-grid",
      shiny::tags$aside(class = "workspace-sidebar",
        shiny::div(class = "surface upload-card", shiny::h3("Add data"),
          shiny::p(class = "muted", "Original files are preserved unchanged."),
          shiny::fileInput(ns("upload"), "Local files", multiple = TRUE,
            buttonLabel = "Choose files", placeholder = "CSV, TSV or ZIP"),
          shiny::textInput(ns("title"), "Collection name", value = "New data"),
          shiny::textInput(ns("actor"), "Operator", value = "local-reviewer"),
          shiny::actionButton(ns("register"), "Register inputs", icon = shiny::icon("plus"), class = "btn-primary full-width"),
          shiny::p(class = "field-help", "Maximum 50 MiB per file, 200 MiB per upload.")),
        shiny::div(class = "surface selection-card", shiny::h3("Registered data"),
          shiny::radioButtons(ns("workspace_filter"), "Show", choices = c("Active" = "active", "Removed" = "removed"), inline = TRUE),
          shiny::selectInput(ns("version"), "Source version", choices = character()),
          shiny::selectInput(ns("resource"), "File", choices = character()),
          shiny::uiOutput(ns("workspace_actions")),
          shiny::actionButton(ns("refresh"), "Refresh list", icon = shiny::icon("rotate"), class = "btn-outline-secondary full-width")),
        shiny::div(class = "sidebar-note", shiny::icon("shield-halved"),
          shiny::span("Original files and configurations are stored separately. Each save creates a revision."))),
      shiny::tags$main(class = "workspace-main",
        shiny::tabsetPanel(id = ns("view"), type = "tabs",
          shiny::tabPanel("Data and configuration", value = "config",
            shiny::div(class = "surface tab-surface", shiny::uiOutput(ns("resource_summary")),
              shiny::div(class = "section-heading", shiny::div(shiny::h2("Reading configuration"),
                shiny::p(class = "muted", "Choose how to read the file while preserving its original bytes."))),
              shiny::selectInput(ns("config"), "Saved revision", choices = character()),
              shiny::uiOutput(ns("parser_form")))),
          shiny::tabPanel("Missing information", value = "clarifications",
            shiny::div(class = "surface tab-surface", shiny::uiOutput(ns("clarification_panel")))),
          shiny::tabPanel("Preview", value = "preview",
            shiny::div(class = "surface tab-surface", shiny::uiOutput(ns("preview_summary")),
              shiny::uiOutput(ns("table_selector")),
              shiny::div(class = "table-scroll", shiny::tableOutput(ns("preview_table"))))),
          shiny::tabPanel("History", value = "history",
            shiny::div(class = "surface tab-surface", shiny::h2("Persistent history"),
              shiny::p(class = "muted", "Every preview uses a specific source version and configuration."),
              shiny::h3("Removal and restoration of the selected version"),
              shiny::div(class = "table-scroll", shiny::tableOutput(ns("workspace_history"))),
              shiny::div(class = "table-scroll", shiny::tableOutput(ns("history_table"))),
              shiny::selectInput(ns("operation"), "Operation details", choices = character()),
              shiny::uiOutput(ns("operation_summary")),
              shiny::div(class = "table-scroll", shiny::tableOutput(ns("events_table")))))))),
    shiny::tags$footer(class = "app-footer", "Lexical preview: this interface does not run scientific checks.")
  )
}
